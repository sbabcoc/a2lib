#!/usr/bin/env python3
#
# Soft-70 font tool (DESIGN.md 3.8)
#
#   s70font.py FONT.txt OUT.s              assembler source of the font
#   s70font.py FONT.txt --bin OUT.70       768-byte period-format file
#   s70font.py FONT.txt --preview OUT.png  glyph sheet and a sample screen
#
# FONT.txt holds 96 glyphs, $20-$7F, each a header line ("41 A") and 8
# rows of 3 characters ('#' lit, '.' unlit) for pixels 1-3 of the cell.
# The period format is 96 x 8 bytes, one byte per scanline, top first,
# bit 0 the leftmost pixel; pixel 0 is the gap, so the glyph is bits 1-3.
#
# Copyright (c) 2026 Scott Babcock. zlib license; see LICENSE.

import sys


def load(path):
    glyphs = []
    lines = [l.rstrip("\n") for l in open(path, encoding="ascii")]
    lines = [l for l in lines if l and not l.startswith(";")]
    i = 0
    while i < len(lines):
        code = int(lines[i].split()[0], 16)
        if code != 0x20 + len(glyphs):
            sys.exit(f"{path}: expected ${0x20 + len(glyphs):02X}, found ${code:02X}")
        rows = lines[i + 1:i + 9]
        if len(rows) != 8 or any(len(r) != 3 or set(r) - set(".#") for r in rows):
            sys.exit(f"{path}: glyph ${code:02X}: need 8 rows of 3 '.'/'#'")
        glyphs.append([sum(2 << b for b, c in enumerate(r) if c == "#") for r in rows])
        i += 9
    if len(glyphs) != 96:
        sys.exit(f"{path}: {len(glyphs)} glyphs, need 96")
    return glyphs


def asm(glyphs, src):
    out = [
        "; Soft-70 default font (DESIGN.md 3.8), in the 768-byte period format:",
        "; 96 characters ($20-$7F) x 8 scanlines, bit 0 leftmost, bits 1-3 lit.",
        f"; Generated by tools/s70font.py from {src}; edit that file instead.",
        ";",
        "; Copyright (c) 2026 Scott Babcock. zlib license; see LICENSE.",
        ";",
        "",
        "        .export         s70_deffont",
        "",
        "        .segment        \"ONCE\"         ; Copied at startup, then reused",
        "",
        "s70_deffont:",
    ]
    for n, g in enumerate(glyphs):
        c = 0x20 + n
        name = {0x20: "space", 0x7F: "DEL"}.get(c, chr(c))
        out.append(f"        .byte   {', '.join(f'${b:02X}' for b in g)}   ; ${c:02X} {name}")
    return "\n".join(out) + "\n"


def preview(glyphs, path):
    from PIL import Image, ImageDraw

    fg, bg, grid = (0x33, 0xFF, 0x66), (0x08, 0x10, 0x08), (0x22, 0x33, 0x22)

    # Glyph sheet: 16 x 6, each 4 x 8 pixels at 10x, cell outlines
    s = 10
    sheet = Image.new("RGB", (16 * 4 * s + 1, 6 * 8 * s + 1), bg)
    d = ImageDraw.Draw(sheet)
    for n, g in enumerate(glyphs):
        cx, cy = (n % 16) * 4 * s, (n // 16) * 8 * s
        d.rectangle([cx, cy, cx + 4 * s, cy + 8 * s], outline=grid)
        for y, b in enumerate(g):
            for x in range(4):
                if b >> x & 1:
                    d.rectangle([cx + x * s + 1, cy + y * s + 1,
                                 cx + (x + 1) * s - 1, cy + (y + 1) * s - 1], fill=fg)

    # Sample 70 x 24 screen, 280 x 192, each pixel 3 x 3
    text = [
        "A2LIB SOFT-70: 70 COLUMNS OF A 80 X 24 SCREEN ON THE APPLE II+ HI-RES PAGE",
        "",
        "The quick brown fox jumps over the lazy dog. THE QUICK BROWN FOX JUMPS.",
        "Descenders: gypsy jiggly quip, Q_ underscores; pack my box with liquor jugs.",
        "",
        "  !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_",
        "  `abcdefghijklmnopqrstuvwxyz{|}~",
        "",
        "]CATALOG",
        "",
        "DISK VOLUME 254",
        "",
        " A 006 HELLO",
        " B 034 TELNET",
        " B 029 GOPHER",
        " T 002 NOTES.TXT",
        "",
        "#include <stdio.h>",
        "int main (void) { printf (\"Hello, world!\\n\"); return 0; }",
        "",
        "gopher://gopher.floodgap.com/1/world  (type 1, port 70)",
        "Login: guest   Password: ******   Last login: Sat Nov 14 12:11",
        "",
        "$ _",
    ]
    p = 3
    scr = Image.new("RGB", (280 * p, 192 * p), bg)
    d = ImageDraw.Draw(scr)
    for row, line in enumerate(text[:24]):
        for col, ch in enumerate(line[:70]):
            g = glyphs[ord(ch) - 0x20]
            for y, b in enumerate(g):
                for x in range(4):
                    if b >> x & 1:
                        px, py = (col * 4 + x) * p, (row * 8 + y) * p
                        d.rectangle([px, py, px + p - 1, py + p - 1], fill=fg)

    gap = 30
    out = Image.new("RGB", (max(sheet.width, scr.width) + 2 * gap,
                            sheet.height + scr.height + 3 * gap), (0, 0, 0))
    out.paste(sheet, (gap, gap))
    out.paste(scr, (gap, sheet.height + 2 * gap))
    out.save(path)


def main():
    if len(sys.argv) != 3 and len(sys.argv) != 4:
        sys.exit(__doc__ or "usage: s70font.py FONT.txt [--bin|--preview] OUT")
    glyphs = load(sys.argv[1])
    if sys.argv[2] == "--preview":
        preview(glyphs, sys.argv[3])
    elif sys.argv[2] == "--bin":
        open(sys.argv[3], "wb").write(bytes(b for g in glyphs for b in g))
    else:
        open(sys.argv[2], "w").write(asm(glyphs, sys.argv[1]))


if __name__ == "__main__":
    main()
