#!/usr/bin/env bash
#
# Check that the working tree generates the same bytes as a commit, for
# changes meant to touch only names, comments and layout (DESIGN.md 1,
# code conventions).
#
#   bash tools/samebytes.sh [REV]       (default: HEAD)
#
# Builds REV in a temporary worktree and the working tree as it is, and
# compares what each generates, without the source text:
#
#   - every module's addresses and bytes, from ca65's listing, assembled
#     with each set of flags the Makefile uses, and for sim6502 where the
#     simulator tests build it
#   - every module's imports, exports and segment sizes (od65)
#   - every C test's generated assembly, under each define the Makefile
#     uses
#   - every linked test and simulator program
#
# Libraries aren't compared: ar65 records each object's source name and
# size, so they differ with any comment; the programs linked from them
# are. Prints IDENTICAL and exits 0, or lists what differs and exits 1.
#
# Needs cc65 on PATH (the commit the libraries are built with), python3,
# and git. Set CC65_LIB if the Makefile's default doesn't find cc65's
# libraries.
#
# Copyright (c) 2026 Scott Babcock. zlib license; see LICENSE.

set -euo pipefail

REV="${1:-HEAD}"
ROOT="$(git rev-parse --show-toplevel)"
TMP="$(mktemp -d)"
trap 'git -C "$ROOT" worktree remove --force "$TMP/rev" >/dev/null 2>&1 || true; rm -rf "$TMP"' EXIT

die() { echo "samebytes: $*" >&2; exit 2; }
command -v ca65 >/dev/null || die "ca65 isn't on PATH"
command -v python3 >/dev/null || die "python3 isn't on PATH"
ASMINC="$(dirname "$(command -v ca65)")/../asminc"
[[ -d "$ASMINC" ]] || ASMINC="$(cl65 --print-target-path)/../asminc"
CINC="$(dirname "$ASMINC")/include"

# fingerprint TREE OUT
fingerprint() {
    local tree="$1" out="$2" s c tgt def
    mkdir -p "$out/asm" "$out/c" "$out/bin"
    (
        cd "$tree"
        local d33="-I libsrc/dos33"
        local vt="-I libsrc/vt -I libsrc/dos33"
        local win="-I libsrc/win -I libsrc/s80 -I libsrc/vt -I libsrc/dos33"
        local s70="-I libsrc/s70 -I libsrc/s80 -I libsrc/vt -I libsrc/dos33"
        local tst="-I test -I test/sim -I libsrc/dos33"
        asm() {  # asm TAG TARGET FLAGS FILE
            local key="${1}_${2}_${4//\//_}"
            ca65 -t "$2" $3 -I "$ASMINC" --list-bytes 0 -l "$out/l.lst" -o "$out/l.o" "$4"
            python3 - "$out/l.lst" > "$out/asm/$key.bytes" <<'PY'
import re, sys
for line in open(sys.argv[1], errors='replace'):
    m = re.match(r'^([0-9A-F]{6})([r ]) +\d+ +((?:(?:[0-9A-F]{2}|rr) )+)', line)
    if m: print(m.group(1) + m.group(2), m.group(3).strip())
PY
            od65 --dump-imports --dump-exports --dump-segsize "$out/l.o" | sed 1d > "$out/asm/$key.syms"
        }
        for s in libsrc/dos33/*.s; do asm d33 apple2 "$d33" "$s"; done
        for s in timer tick kbhit gettime settime reflow; do asm d33 sim6502 "$d33" "libsrc/dos33/$s.s"; done
        for s in libsrc/vt/*.s; do asm vt apple2 "$vt" "$s"; done
        for s in libsrc/ip65/*.s; do asm ip65 apple2 "$d33" "$s"; done
        for s in libsrc/win/*.s libsrc/s80/*.s; do asm win apple2 "$win" "$s"; asm win sim6502 "$win" "$s"; done
        for s in libsrc/s70/*.s libsrc/s80/*.s; do asm s70 apple2 "$s70" "$s"; asm s70 sim6502 "$s70" "$s"; done
        for s in test/*.s; do asm tst apple2 "$tst" "$s"; done
        for s in test/sim/*.s; do asm tst sim6502 "$tst" "$s"; done
        for c in test/*.c test/sim/*.c; do
            tgt=apple2; [[ "$c" == test/sim/* ]] && tgt=sim6502
            for def in "" -DRAW -DEXECA -DC40WIN -DS70; do
                cc65 -t $tgt -O -I include -I "$CINC" $def -o "$out/c.s" "$c" >/dev/null 2>&1 || continue
                grep -v '^; File generated by' "$out/c.s" > "$out/c/${c//\//_}$def.s"
            done
        done
        rm -rf build lib
        make -s all test simtest > "$out/make.log" 2>&1 || { tail "$out/make.log" >&2; exit 1; }
        for f in build/test/* build/sim/*sim; do
            case "$f" in *.map) continue ;; esac
            [[ -f "$f" ]] && cp "$f" "$out/bin/"
        done
        rm -rf build lib
    ) || die "couldn't build $tree"
    rm -f "$out/l.lst" "$out/l.o" "$out/c.s" "$out/make.log"
}

git -C "$ROOT" worktree add --detach "$TMP/rev" "$REV" >/dev/null 2>&1 || die "no such revision: $REV"
rsync -a --delete --exclude .git --exclude build --exclude lib "$ROOT/" "$TMP/now/" 2>/dev/null \
    || { mkdir -p "$TMP/now"; (cd "$ROOT" && tar --exclude=.git --exclude=build --exclude=lib -cf - .) | tar -C "$TMP/now" -xf -; }

fingerprint "$TMP/rev" "$TMP/fp-rev"
fingerprint "$TMP/now" "$TMP/fp-now"

if diff -rq "$TMP/fp-rev" "$TMP/fp-now"; then
    echo "IDENTICAL to $(git -C "$ROOT" rev-parse --short "$REV")"
else
    echo "DIFFERENT from $(git -C "$ROOT" rev-parse --short "$REV")"
    exit 1
fi
